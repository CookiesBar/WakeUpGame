// rn.mjs: writes components/wakey/rig.ts, the app's copy of the rig (static art, expression shapes, walk tokens).
// Run after build.mjs and walk.mjs, from the repo root: node assets/mascots/face-rig/tools/rn.mjs
// Reads ../face-rig.svg, ../face-rig.json and ../walk-cycle.json. Never edit rig.ts by hand.
import fs from 'fs';
import path from 'path';
const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1'));
const RIG = path.join(HERE, '..');
const OUT = path.join(RIG, '..', '..', '..', 'components', 'wakey', 'rig.ts');

const svg = fs.readFileSync(path.join(RIG, 'face-rig.svg'), 'utf8');
const rig = JSON.parse(fs.readFileSync(path.join(RIG, 'face-rig.json'), 'utf8'));
const walk = JSON.parse(fs.readFileSync(path.join(RIG, 'walk-cycle.json'), 'utf8'));
const NUM = /-?\d*\.?\d+(?:e-?\d+)?/g;

function grab(id) {
  const start = svg.indexOf(`<g id="${id}"`);
  if (start < 0) throw new Error('no part ' + id);
  const re = /<g[\s>]|<\/g>/g;
  re.lastIndex = start;
  let m, depth = 0;
  while ((m = re.exec(svg)) !== null) { depth += m[0] === '</g>' ? -1 : 1; if (depth === 0) return svg.slice(start, m.index + 4); }
  throw new Error('unclosed ' + id);
}
/** A static part: its flat-filled paths, [d, fill]. */
function paths(id) {
  const g = grab(id);
  const out = [...g.matchAll(/<path d="([^"]+)" fill="([^"]+)"\/>/g)].map((m) => [m[1], m[2]]);
  if (out.length !== (g.match(/<path/g) || []).length) throw new Error(`${id}: a path is not a plain d + fill`);
  return out;
}
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
/** The live element's drawing attributes (fill, stroke…), as react-native-svg props. */
function style(tid) {
  const m = svg.match(new RegExp(`<path id="${tid}" ([^>]*?)/?>`));
  if (!m) throw new Error('no target ' + tid);
  const props = {};
  for (const [, k, v] of m[1].matchAll(/([\w-]+)="([^"]*)"/g)) {
    if (['d', 'opacity', 'clip-path'].includes(k)) continue;
    props[camel(k)] = /^-?\d*\.?\d+$/.test(v) ? +v : v;
  }
  return props;
}

function family(fam) {
  const list = rig.expressions[fam];
  const targets = Object.keys(list[0].targets);
  const cmds = targets.map((t) => list[0].targets[t].d.replace(NUM, '').replace(/[\s,]/g, ''));
  const shapes = {};
  for (const e of list) {
    shapes[e.name] = targets.map((t, i) => {
      const { d, opacity } = e.targets[t];
      if (d.replace(NUM, '').replace(/[\s,]/g, '') !== cmds[i]) throw new Error(`${fam} ${e.name} ${t}: commands differ`);
      return [...d.match(NUM).map(Number), opacity];
    });
  }
  return { targets, cmds, style: targets.map(style), shapes };
}

const eyes = family('eyes');
const mouth = family('mouth');
const hand = (id) => ({ paths: paths(id), rest: rig.parts.find((p) => p.id === id).restAngle });
const data = {
  VIEWBOX: walk.viewBox,
  PIVOT: { bellLeft: rig.parts.find((p) => p.id === 'bell-left').pivot, bellRight: rig.parts.find((p) => p.id === 'bell-right').pivot, hub: rig.parts.find((p) => p.id === 'hub').pivot },
  ART: {
    bellLeft: paths('bell-left'),
    bellRight: paths('bell-right'),
    head: ['body-back', 'ring', 'face', 'face-shadow', 'ticks', 'markers', 'cheeks'].flatMap(paths),
    handShort: hand('hand-short'),
    handLong: hand('hand-long'),
    hub: paths('hub'),
  },
  EYES: eyes,
  MOUTH: mouth,
  WALK: { tokens: walk.tokens, keys: Object.fromEntries(Object.entries(walk.keys).filter(([, v]) => typeof v !== 'string')), restFrameMs: walk.restFrameMs, face: walk.face.rules },
};

const names = (f) => Object.keys(f.shapes).map((n) => `'${n}'`).join(' | ');
let ts = `// GENERATED by assets/mascots/face-rig/tools/rn.mjs from face-rig.svg, face-rig.json and walk-cycle.json.\n// Don't edit: change the rig's generators, rerun them, then rerun rn.mjs.\n/* eslint-disable */\n`;
ts += `export type EyeName = ${names(eyes)};\nexport type MouthName = ${names(mouth)};\n`;
ts += `/** Expression data: per target, the path's numbers in order, then its opacity. Every expression of a family shares the targets' commands. */\nexport type Family<N extends string> = { targets: readonly string[]; cmds: readonly string[]; style: readonly Record<string, string | number>[]; shapes: Record<N, number[][]> };\n`;
for (const [k, v] of Object.entries(data)) {
  const type = k === 'EYES' ? ': Family<EyeName>' : k === 'MOUTH' ? ': Family<MouthName>' : '';
  ts += `export const ${k}${type} = ${JSON.stringify(v)}${type ? '' : ' as const'};\n`;
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, ts);
console.log('written', path.relative(process.cwd(), OUT), fs.statSync(OUT).size, 'bytes;', Object.keys(eyes.shapes).length, 'eyes,', Object.keys(mouth.shapes).length, 'mouths');
